"""FROZEN JUDGE (step 2): data, folds, holdout, metric and guardrails.

This file must not be modified by whoever experiments (human or agent): it defines what
"better" means. Experiments happen only in train.py.

- Time folds: F2023 = fit on 2021-22, evaluate on 2023; F2024 = fit on 2021-23, evaluate on 2024.
- Closed holdout: 10% of policies (stable hash of policy_id), excluded from fitting and from fold
  evaluation; looked at only at the end of the work (holdout_score).
- Target: target_b (ultimate per row at the 2025 level, capped + large-loss loading).
- Metric: Tweedie D² with power 1.5 on per-row predictions (CU), as on Kaggle.
- Guardrail: only columns in the allowed list may enter the model.
"""
import hashlib
from pathlib import Path

import numpy as np
import pandas as pd

import sys
sys.path.insert(0, str(Path(__file__).parent))
from market_config import CFG, LINES, folds_from_years  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MODEL_DIR = Path(CFG["model_dir"])
RESULTS = Path(CFG["results"])


def _years():
    try:
        return sorted(int(y) for y in pd.read_parquet(MODEL_DIR / f"model_{LINES[0]}.parquet", columns=["year"])["year"].unique())
    except Exception:
        return [2021, 2022, 2023, 2024]


FOLDS = folds_from_years(_years())
HOLDOUT_SHARE = float(CFG["holdout_share"])
TARGET = "target_b"
POWER = 1.5

FORBIDDEN_PREFIX = ("n_", "cost_", "excess_", "pi_", "ult", "target", "flag_")
FORBIDDEN = {"renewal_decision", "written_premium", "rec_adj", "n_total", "cost_total", "year",
             "period_start", "period_end", "exposure", "exposure_raw", "row_id", "policy_id",
             "customer_id", "address_id", "construction_type_raw", "email_domain", "surname",
             "date_of_birth", "customer_since_year", "year_built", "birth_year",
             "pol_prev_n", "pol_prev_cost", "cust_other_prev_n", "cust_other_prev_cost",
             "addr_prev_n", "addr_prev_cost",   # raw counts: longer history in the test set -> use the rates
             # LEAKAGE: customer-service contacts DURING the row's period, generated by the claims themselves
             # (0 contacts -> frequency 0.03%; corr. 0.75 with claim count; in the 2025 test max 6 vs 36)
             "customer_service_contacts"}


def drift_report(line: str) -> pd.DataFrame:
    """Guardrail: compares each allowed variable between training 2024 and test 2025 (PSI on 10 bins).
    PSI > 0.25 = very different distribution: possibly information not available at pricing time."""
    tr = load(line); tr = tr[tr["year"] == 2024]; te = load(line, "test")
    rows = []
    for c in allowed_features(tr):
        a, b = tr[c], te[c]
        if pd.api.types.is_numeric_dtype(a) and a.nunique() > 10:
            edges = np.unique(np.nanquantile(a.astype(float), np.linspace(0, 1, 11)))
            pa = np.histogram(a.dropna().astype(float), edges)[0] + 1; pb = np.histogram(b.dropna().astype(float), edges)[0] + 1
        else:
            norm = lambda x: x.map(lambda v: str(round(float(v), 6)) if isinstance(v, (int, float, np.number)) and not isinstance(v, bool) else str(v))
            va, vb = norm(a).value_counts(), norm(b).value_counts()
            k = va.index.union(vb.index); pa = va.reindex(k).fillna(0).to_numpy() + 1; pb = vb.reindex(k).fillna(0).to_numpy() + 1
        pa, pb = pa / pa.sum(), pb / pb.sum()
        rows.append((c, float(np.sum((pa - pb) * np.log(pa / pb)))))
    return pd.DataFrame(rows, columns=["feature", "psi"]).sort_values("psi", ascending=False)


def tweedie_deviance(y, mu, p=POWER):
    y = np.asarray(y, float); mu = np.clip(np.asarray(mu, float), 1e-9, None)
    return float(np.mean(2 * (np.power(np.maximum(y, 0), 2 - p) / ((1 - p) * (2 - p))
                              - y * np.power(mu, 1 - p) / (1 - p) + np.power(mu, 2 - p) / (2 - p))))


def d2(y, mu):
    y = np.asarray(y, float)
    return 1 - tweedie_deviance(y, mu) / tweedie_deviance(y, np.full_like(y, y.mean()))


def is_holdout(policy_id: pd.Series) -> np.ndarray:
    h = policy_id.map(lambda s: int(hashlib.md5(s.encode()).hexdigest()[:8], 16) / 0xFFFFFFFF)
    return (h < HOLDOUT_SHARE).to_numpy()


def allowed_features(df: pd.DataFrame) -> list:
    return [c for c in df.columns if c not in FORBIDDEN and not c.startswith(FORBIDDEN_PREFIX)]


def check_features(cols, df) -> None:
    bad = [c for c in cols if c in FORBIDDEN or c.startswith(FORBIDDEN_PREFIX) or c not in df.columns]
    if bad:
        raise ValueError(f"columns not allowed in the model: {bad}")


_JOWN = None


def d2_own(row_id, pred):
    """Secondary judge without smoothing (19/10, src/judge_own.py): D² between developed reported cost and
    (pred − LL) × expected completeness, level realigned. None if judge_own.parquet does not exist for the market.
    Avoids rewarding flat predictions when the spread IBNR weighs a lot (recent years, Part 2)."""
    global _JOWN
    if _JOWN is None:
        f = RESULTS / "judge_own.parquet"
        _JOWN = pd.read_parquet(f).set_index("row_id") if f.exists() else False
    if _JOWN is False:
        return None
    j = _JOWN.reindex(np.asarray(row_id))
    attr = np.clip(np.asarray(pred, float) - j["ll_expo"].to_numpy(), 1e-3, None) * j["pi_eff"].to_numpy()
    y = j["target_rep"].to_numpy()
    return d2(y, attr * y.sum() / attr.sum())


_JUNC = None


def d2_unc(row_id, pred):
    """Third judge (20/10, src/judge_unc.py): target with the actual large losses (reported attritional + excess over the
    cap), prediction × expected completeness, level realigned. Used to assess the allocation of the large-loss loading."""
    global _JUNC
    if _JUNC is None:
        f = RESULTS / "judge_unc.parquet"
        _JUNC = pd.read_parquet(f).set_index("row_id")["excess_onl"] if f.exists() else False
    if _JUNC is False or d2_own(row_id, pred) is None:
        return None
    j = _JOWN.reindex(np.asarray(row_id))
    y = j["target_rep"].to_numpy() + _JUNC.reindex(np.asarray(row_id)).fillna(0).to_numpy()
    mu = np.asarray(pred, float) * j["pi_eff"].to_numpy()
    return d2(y, mu * y.sum() / mu.sum())


def load(line: str, kind: str = "train") -> pd.DataFrame:
    return pd.read_parquet(MODEL_DIR / f"{'model' if kind == 'train' else 'test'}_{line}.parquet")


def evaluate(fit_predict, lines=LINES, folds=FOLDS, verbose=True):
    """fit_predict(train_df, valid_df, line) -> per-row predictions (CU) on valid_df.
    Returns a dict with D² by line × fold and the weighted mean (the score to optimise)."""
    res, res_own, pooled = {}, {}, {f: ([], []) for f in folds}
    for line in lines:
        df = load(line)
        ho = is_holdout(df["policy_id"])
        df = df[~ho]
        for fname, (tr_years, va_year) in folds.items():
            tr = df[df["year"].isin(tr_years)]
            va = df[df["year"] == va_year]
            pred = np.asarray(fit_predict(tr, va, line), float)
            if (pred < 0).any() or not np.isfinite(pred).all():
                raise ValueError("negative or non-finite predictions")
            res[(line, fname)] = d2(va[TARGET].to_numpy(), pred)
            own = d2_own(va["row_id"], pred)
            if own is not None:
                res_own[(line, fname)] = own
            pooled[fname][0].append(va[TARGET].to_numpy()); pooled[fname][1].append(pred)
            if verbose:
                print(f"  {line:9s} {fname}: D2 = {res[(line, fname)]:.4f}"
                      + (f"  (without smoothing {own:.4f})" if own is not None else ""), flush=True)
    # mean with weights = number of 2025 test rows per line (as Kaggle counts all rows together)
    w = {l: len(load(l, "test")) for l in lines}   # as Kaggle counts: test rows per line
    score = sum(res[(l, f)] * w[l] for l in lines for f in folds) / (sum(w[l] for l in lines) * len(folds))
    # as on Kaggle: all lines together in a single file
    pool = {f: round(d2(np.concatenate(a), np.concatenate(b)), 5) for f, (a, b) in pooled.items()} if len(lines) == len(LINES) else {}
    if verbose and pool:
        print("  pooled (all lines):", pool, flush=True)
    out = {"by": {f"{l}|{f}": round(v, 5) for (l, f), v in res.items()}, "score": round(score, 5), "pooled": pool,
           "pooled_mean": round(float(np.mean(list(pool.values()))), 5) if pool else None}
    if len(res_own) == len(res):
        out["by_own"] = {f"{l}|{f}": round(v, 5) for (l, f), v in res_own.items()}
        out["score_own"] = round(sum(res_own[(l, f)] * w[l] for l in lines for f in folds) / (sum(w[l] for l in lines) * len(folds)), 5)
    return out


def holdout_score(fit_predict, lines=LINES):
    """To be used only at the end of the work: fit on 2021-23 without holdout, evaluate on the 2024 holdout."""
    out = {}
    for line in lines:
        df = load(line)
        ho = is_holdout(df["policy_id"])
        tr = df[(~ho) & df["year"].isin([2021, 2022, 2023])]
        va = df[ho & (df["year"] == 2024)]
        out[line] = round(d2(va[TARGET].to_numpy(), fit_predict(tr, va, line)), 5)
    return out
